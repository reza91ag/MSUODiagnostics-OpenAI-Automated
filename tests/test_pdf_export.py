"""Dependency-free PDF export tests; run on the Windows self-hosted runner."""
import unittest

from pdf_export import render_pdf


class PdfExportTests(unittest.TestCase):
    def setUp(self):
        self.data = {
            "generated_utc": "2026-11-20T15:00:00+00:00",
            "selected_operation": "UpdateDashboard CRUD",
            "window": 50,
            "total_requests": 8,
            "groups": [
                {"label": "Cold / Offline-first", "n": 5,
                 "latest_ms": 2050, "mean_ms": 2906.8, "p95_ms": 4216.2,
                 "median_ms": 2081, "stddev_ms": 1050.5,
                 "divergence_ms": -856.8, "divergence_pct": -29.48},
                {"label": "Warm / Direct cloud", "n": 0,
                 "latest_ms": None, "mean_ms": None, "p95_ms": None,
                 "median_ms": None, "stddev_ms": None,
                 "divergence_ms": None, "divergence_pct": None},
            ],
            "sources": [{"name": "OptiSpec_100% & Core", "persistence": "direct",
                         "files": 2, "requests": 4}],
            "recent": [{"end_utc": "2026-11-20T15:00:00+00:00",
                        "source": "OptiSpec", "operation": "UpdateDashboard CRUD",
                        "persistence": "direct", "duration_ms": 2050,
                        "startup": "cold"}],
        }

    def test_pdf_is_valid_and_contains_numeric_results(self):
        pdf = render_pdf(self.data)
        self.assertTrue(pdf.startswith(b"%PDF-1.4"))
        self.assertTrue(pdf.rstrip().endswith(b"%%EOF"))
        self.assertIn(b"xref\n0 ", pdf)
        self.assertIn(b"This report has been generated by MSUO Diagnostics Dashboard.", pdf)
        self.assertEqual(pdf.count(b"This report has been generated by MSUO Diagnostics Dashboard."), 1)
        self.assertIn(b"2050.00", pdf)
        self.assertIn(b"2906.80", pdf)
        self.assertIn(b"-29.48", pdf)
        self.assertIn(b"UpdateDashboard CRUD", pdf)
        self.assertIn(b"OptiSpec_100% & Core", pdf)
        self.assertNotIn(b"C:\\Private\\Logs", pdf)

    def test_empty_measurements_and_sources(self):
        self.data["sources"] = []
        self.data["recent"] = []
        for group in self.data["groups"]:
            group.update(n=0, latest_ms=None, mean_ms=None, p95_ms=None,
                         median_ms=None, stddev_ms=None, divergence_ms=None,
                         divergence_pct=None)
        pdf = render_pdf(self.data)
        self.assertIn(b"%PDF-1.4", pdf)
        self.assertIn(b"--", pdf)

    def test_large_recent_table_paginates(self):
        self.data["recent"] *= 40
        pdf = render_pdf(self.data)
        self.assertGreaterEqual(pdf.count(b"/Type /Page /Parent"), 2)
        self.assertIn(b"\\(continued\\)", pdf)


if __name__ == "__main__":
    unittest.main()