import unittest

from latex_export import escape_latex, render_latex


class LatexExportTests(unittest.TestCase):
    def setUp(self):
        self.data = {
            "generated_utc": "2026-11-20T15:00:00+00:00",
            "selected_operation": "all",
            "window": 50,
            "total_requests": 8,
            "groups": [
                {
                    "label": "Cold / Offline-first", "n": 5,
                    "latest_ms": 2050, "mean_ms": 2906.8,
                    "p95_ms": 4216.2, "median_ms": 2081,
                    "stddev_ms": 1050.5, "divergence_ms": -856.8,
                    "divergence_pct": -29.48,
                },
                {
                    "label": "Warm / Direct cloud", "n": 0,
                    "latest_ms": None, "mean_ms": None,
                    "p95_ms": None, "median_ms": None,
                    "stddev_ms": None, "divergence_ms": None,
                    "divergence_pct": None,
                },
            ],
            "sources": [
                {"name": "OptiSpec_100% & Core", "persistence": "direct", "files": 2, "requests": 4},
            ],
        }

    def test_escapes_latex_reserved_characters(self):
        self.assertEqual(escape_latex("A_B&C%#${}~^" + chr(92)),
                         r"A\_B\&C\%\#\$\{\}\textasciitilde{}\textasciicircum{}\textbackslash{}")

    def test_paper_ready_tables_and_only_requested_sentence(self):
        tex = render_latex(self.data)
        self.assertIn(r"\section{MSUO Diagnostics Dashboard}", tex)
        self.assertEqual(tex.count("This Section was generated by MSUO Diagnostics Dashboard."), 1)
        self.assertIn(r"OptiSpec\_100\% \& Core", tex)
        self.assertIn("Cold / Offline-first & 5 & 2050.00 & 2906.80 & 4216.20", tex)
        self.assertIn("Warm / Direct cloud & 0 & -- & -- & --", tex)
        self.assertIn("-856.80 & -29.48", tex)
        self.assertEqual(tex.count(r"\begin{table}"), 4)
        self.assertEqual(tex.count(r"\end{table}"), 4)
        self.assertNotIn(r"C:\Private\Logs", tex)
        self.assertNotIn("\\usepackage", tex)
        self.assertNotIn("\\begin{document}", tex)

    def test_selected_operation_and_all_window(self):
        self.data["selected_operation"] = "UpdateDashboard CRUD"
        self.data["window"] = 0
        tex = render_latex(self.data)
        self.assertIn("Operation & UpdateDashboard CRUD", tex)
        self.assertIn("Window & All requests", tex)

    def test_empty_sources_still_exports(self):
        self.data["sources"] = []
        tex = render_latex(self.data)
        self.assertEqual(tex.count(r"\begin{table}"), 3)


if __name__ == "__main__":
    unittest.main()