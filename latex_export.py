"""LaTeX table export of already-computed MSUO Observatory measurements."""
from __future__ import annotations


_ESCAPE = {
    "\\": r"\textbackslash{}",
    "&": r"\&",
    "%": r"\%",
    "$": r"\$",
    "#": r"\#",
    "_": r"\_",
    "{": r"\{",
    "}": r"\}",
    "~": r"\textasciitilde{}",
    "^": r"\textasciicircum{}",
}


def escape_latex(value):
    return "".join(_ESCAPE.get(char, char) for char in str(value))


def fmt(value):
    return "--" if value is None else f"{value:.2f}"


def _table(caption, label, columns, header, rows):
    lines = [
        r"\begin{table}[htbp]",
        r"\centering",
        r"\small",
        rf"\caption{{{caption}}}",
        rf"\label{{{label}}}",
        rf"\begin{{tabular}}{{{columns}}}",
        r"\hline",
        header + " " + r"\\",
        r"\hline",
    ]
    lines.extend(row + r" \\" for row in rows)
    lines += [
        r"\hline",
        r"\end{tabular}",
        r"\end{table}",
    ]
    return "\n".join(lines)


def render_latex(data):
    """Return a paper-ready LaTeX section with labels and numeric tables only."""
    operation = data["selected_operation"]
    window = data["window"]
    meta_rows = [
        "Operation & " + escape_latex("All operations" if operation == "all" else operation),
        "Window & " + ("All requests" if window == 0 else f"Last {window} per configuration"),
        "Total lifecycles & " + str(data["total_requests"]),
        "Generated (UTC) & " + escape_latex(data["generated_utc"]),
    ]
    rows1 = []
    rows2 = []
    for group in data["groups"]:
        name = escape_latex(group["label"])
        rows1.append(" & ".join([
            name, str(group["n"]), fmt(group["latest_ms"]),
            fmt(group["mean_ms"]), fmt(group["p95_ms"]),
        ]))
        rows2.append(" & ".join([
            name, fmt(group["median_ms"]), fmt(group["stddev_ms"]),
            fmt(group["divergence_ms"]), fmt(group["divergence_pct"]),
        ]))
    sources = []
    for source in data["sources"]:
        sources.append(" & ".join([
            escape_latex(source["name"]),
            escape_latex(source["persistence"] or "--"),
            str(source["files"]), str(source["requests"]),
        ]))
    parts = [
        r"\section{MSUO Diagnostics Dashboard}",
        "This Section was generated by MSUO Diagnostics Dashboard.",
        "",
        _table("Measurement selection", "tab:msuo-selection", "ll",
               "Parameter & Value", meta_rows),
        "",
        _table("Lifecycle latency by configuration (ms)", "tab:msuo-latency", "lrrrr",
               "Configuration & $n$ & Latest & Mean & P95", rows1),
        "",
        _table("Latency dispersion and divergence", "tab:msuo-divergence", "lrrrr",
               r"Configuration & Median (ms) & SD (ms) & $\Delta$ (ms) & $\Delta$ (\%)", rows2),
        "",
    ]
    if sources:
        parts.extend([
            _table("Measurement sources", "tab:msuo-sources", "llrr",
                   "Source & Persistence & Files & Lifecycles", sources),
            "",
        ])
    return "\n".join(parts)