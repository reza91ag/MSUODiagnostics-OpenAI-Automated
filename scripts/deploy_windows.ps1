# Deploy application files while preserving production WatchDog configuration.
[CmdletBinding()]
param(
    [string]$Destination = 'C:\MSUO\Observatory',
    [string]$TaskName = 'MSUO-Observatory',
    [int]$Port = 8765
)
$ErrorActionPreference = 'Stop'
$repo = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
$files = @('latex_export.py', 'server.py', 'web\msuo-logo.svg', 'web\index.html')
foreach ($relative in $files) {
    if (-not (Test-Path -LiteralPath (Join-Path $repo $relative))) {
        throw "Application source is missing: $relative"
    }
}
$task = Get-ScheduledTask -TaskName $TaskName -ErrorAction SilentlyContinue
if ($null -eq $task) {
    throw "Scheduled task '$TaskName' is not installed. Run scripts/setup_windows_task.ps1 as Administrator on the server first."
}
New-Item -ItemType Directory -Force -Path $Destination | Out-Null
New-Item -ItemType Directory -Force -Path (Join-Path $Destination 'web') | Out-Null

# Back up only deployed application files. Never modify msuo_live_config.json.
$backup = Join-Path $env:TEMP ("msuo-observatory-backup-" + [guid]::NewGuid().ToString('N'))
foreach ($relative in $files) {
    $existing = Join-Path $Destination $relative
    if (Test-Path -LiteralPath $existing) {
        $old = Join-Path $backup $relative
        New-Item -ItemType Directory -Force -Path (Split-Path -Parent $old) | Out-Null
        Copy-Item -LiteralPath $existing -Destination $old -Force
    }
}

function Wait-ForDashboard([int]$TimeoutSeconds) {
    for ($i = 0; $i -lt $TimeoutSeconds; $i++) {
        Start-Sleep -Seconds 1
        try {
            $page = Invoke-WebRequest -Uri "http://127.0.0.1:$Port/" -UseBasicParsing -TimeoutSec 2
            $latex = Invoke-WebRequest -Uri "http://127.0.0.1:$Port/api/export.tex" -UseBasicParsing -TimeoutSec 2
            $logo = Invoke-WebRequest -Uri "http://127.0.0.1:$Port/assets/msuo-logo.svg" -UseBasicParsing -TimeoutSec 2
            if ($page.StatusCode -eq 200 -and $page.Content -match 'MSUO' -and
                $latex.StatusCode -eq 200 -and $latex.Content -match 'This Section was generated by MSUO Diagnostics Dashboard' -and
                $logo.StatusCode -eq 200 -and $logo.Content -match '<svg') {
                return $true
            }
        } catch { }
    }
    return $false
}

try {
    if ((Get-ScheduledTask -TaskName $TaskName).State -eq 'Running') {
        Stop-ScheduledTask -TaskName $TaskName
        Start-Sleep -Seconds 2
    }
    foreach ($relative in $files) {
        Copy-Item -LiteralPath (Join-Path $repo $relative) -Destination (Join-Path $Destination $relative) -Force
    }
    Start-ScheduledTask -TaskName $TaskName
    if (-not (Wait-ForDashboard -TimeoutSeconds 20)) {
        throw "Dashboard, LaTeX export, or logo did not become healthy on 127.0.0.1:$Port"
    }
    Write-Host "Deployment successful: http://127.0.0.1:$Port"
    Write-Host "LaTeX export: http://127.0.0.1:$Port/api/export.tex"
} catch {
    Write-Warning "Deployment failed: $($_.Exception.Message). Attempting rollback."
    try {
        Stop-ScheduledTask -TaskName $TaskName -ErrorAction SilentlyContinue
        foreach ($relative in $files) {
            $old = Join-Path $backup $relative
            $dest = Join-Path $Destination $relative
            if (Test-Path -LiteralPath $old) {
                Copy-Item -LiteralPath $old -Destination $dest -Force
            } else {
                Remove-Item -LiteralPath $dest -Force -ErrorAction SilentlyContinue
            }
        }
        if ((Test-Path -LiteralPath (Join-Path $Destination 'server.py')) -and
            (Test-Path -LiteralPath (Join-Path $Destination 'web\index.html'))) {
            Start-ScheduledTask -TaskName $TaskName
        }
    } catch {
        Write-Warning "Rollback also failed: $($_.Exception.Message)"
    }
    throw
} finally {
    Remove-Item -LiteralPath $backup -Recurse -Force -ErrorAction SilentlyContinue
}
